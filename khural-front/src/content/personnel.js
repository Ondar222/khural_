export const PERSONNEL_DOCS_BASE = "/docs/personnel";

/**
 * Пункт списка документов раздела.
 * PDF открывается в предпросмотре на сайте (data-doc-preview читается PageBySlug),
 * data-no-spa отключает перехват ссылки роутером, скачивание — отдельной ссылкой.
 * Остальные форматы (.docx, .rtf) браузер не показывает, поэтому сразу скачиваются.
 */
export function personnelDocItem(title, file) {
  const url = `${PERSONNEL_DOCS_BASE}/${file}`;
  const safeTitle = String(title).replace(/"/g, "&quot;");
  if (!/\.pdf$/i.test(file)) {
    return `<li><a href="${url}" download style="color: #003366;">${title}</a></li>`;
  }
  return `<li><a href="${url}" data-no-spa="1" data-doc-preview="1" data-doc-title="${safeTitle}" style="color: #003366;">${title}</a>` +
    ` <a href="${url}" download title="Скачать документ" style="color: #6b7280; font-size: 13px;">(скачать)</a></li>`;
}

