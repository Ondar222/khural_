/** Страница раздела по slug: { title, html } или null. */
export function getPersonnelPage(slug) {
  if (!slug) return null;
  const key = String(slug).replace(/^\/+|\/+$/g, "");
  if (key === INFO_PERSONNEL_SLUG) {
    return { title: INFO_PERSONNEL_TITLE, html: INFO_PERSONNEL_HTML };
  }
  const found = PERSONNEL_SECTIONS.find((s) => s.slug === key);
  return found ? { title: found.title, html: found.html } : null;
}

/** True, если slug относится к разделу «Кадровое обеспечение». */
export function isPersonnelSlug(slug) {
  return PERSONNEL_SLUGS.includes(String(slug || "").replace(/^\/+|\/+$/g, ""));
}
